-- Миграция 061: Обновление функции accept_order для поддержки активации отмененных заказов
-- Функция теперь может принимать заказы со статусом cancelled (если они были активированы)

-- Функция accept_order уже проверяет статус searching_courier, поэтому
-- отмененные заказы нужно сначала активировать (изменить статус на searching_courier),
-- а затем принять через эту функцию

-- Никаких изменений в функции не требуется, так как активация происходит на клиенте
-- перед вызовом accept_order

COMMENT ON FUNCTION public.accept_order(UUID, UUID) IS 'Принимает заказ водителем. Заказ должен иметь статус searching_courier. Для активации отмененного заказа сначала измените его статус на searching_courier, затем вызовите эту функцию.';

